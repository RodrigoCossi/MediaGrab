def svg(name: str, color: str = "#e8eaf0", width: float = 2.0, fill: bool = False) -> bytes:
    f = color if fill else "none"
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="{f}" stroke="{color}" '
            f'stroke-width="{width}" stroke-linecap="round" stroke-linejoin="round">{P[name]}</svg>').encode()


def pixmap(name: str, size: int, color: str = "#e8eaf0", ratio: float = 1.0, **kw) -> QPixmap:
    px = QPixmap(int(size * ratio), int(size * ratio))
    px.fill(Qt.transparent)
    r = QSvgRenderer(QByteArray(svg(name, color, **kw)))
    p = QPainter(px)
    p.setRenderHint(QPainter.Antialiasing)
    r.render(p, QRectF(0, 0, px.width(), px.height()))
    p.end()
    px.setDevicePixelRatio(ratio)
    return px


def icon(name: str, color: str = "#e8eaf0", **kw) -> QIcon:
    ic = QIcon()
    for s in (16, 24, 32, 48, 64):
        ic.addPixmap(pixmap(name, s, color, **kw))
    return ic
